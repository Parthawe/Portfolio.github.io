import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5222'
const out = process.env.QA_OUTPUT_DIR || '/tmp/portfolio-site-refinement'
mkdirSync(out, { recursive: true })
const browser = await chromium.launch(), results = []
try {
  for (const [width, theme] of [[1440,'light'], [768,'dark'], [390,'light']]) {
    const context = await browser.newContext({ viewport: {width, height: 960}, reducedMotion: 'reduce', hasTouch: width < 900 })
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.addInitScript(theme => localStorage.setItem('theme', theme), theme)
    const overflow = async name => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${name} overflow at ${width}`)
    await page.goto(base + '/work', {waitUntil:'domcontentloaded'})
    await expect(page.getByRole('heading',{name:'Work',exact:true})).toBeVisible()
    await expect(page.locator('.work-mobile-views')).toBeVisible()
    await expect(page.locator('.nav-work-views')).toHaveCount(0)
    await page.evaluate(() => document.fonts.ready)
    const before = await page.locator('.nav-left-pill').boundingBox()
    const alignment = await page.locator('.work-page-summary').evaluate(el => getComputedStyle(el).textAlign)
    assert.equal(alignment, width > 900 ? 'right' : 'left')
    await page.evaluate(() => window.scrollTo(0, 600))
    await expect(page.locator('.nav')).toHaveClass(/scrolled-deep/)
    const after = await page.locator('.nav-left-pill').boundingBox()
    assert(Math.abs(before.x - after.x) < 1 && Math.abs(before.width - after.width) < 1, 'nav shrinks or shifts on scroll')
    await overflow('Work')
    await page.evaluate(() => window.scrollTo(0,0))
    await page.screenshot({path:`${out}/work-${width}.png`})
    await page.goto(base + '/about#recognition', {waitUntil:'domcontentloaded'})
    await expect(page.locator('.abt-recognition-row')).toHaveCount(7)
    await expect(page.locator('.abt-award-card')).toHaveCount(0)
    await expect(page.locator('.abt-vibe .abt-build-practice')).toHaveCount(1)
    await expect(page.locator('.abt-codex')).toHaveCount(0)
    await page.evaluate(() => document.fonts.ready)
    const aboutNav = await page.locator('.nav-left-pill').boundingBox()
    assert(Math.abs(aboutNav.width - before.width) < 1, `nav changes width between Work and About at ${width}px: ${before.width} → ${aboutNav.width}`)
    await page.locator('#recognition').scrollIntoViewIfNeeded()
    await page.screenshot({path:`${out}/about-${width}.png`})
    await overflow('About')
    await page.goto(base + '/notes', {waitUntil:'domcontentloaded'})
    await expect(page.locator('[data-note-kind="example"]')).toHaveCount(6)
    await expect(page.locator('.note-sample')).toHaveCount(0)
    await page.getByRole('button', {name:'Hide examples',exact:true}).click()
    await expect(page.locator('[data-note-kind="example"]')).toHaveCount(0)
    await page.getByRole('button', {name:'Show examples',exact:true}).click()
    await overflow('Notes')
    await page.screenshot({path:`${out}/notes-${width}.png`})
    await page.goto(base + '/mentra#decision-runtime', {waitUntil:'domcontentloaded'})
    const chapter = page.locator('#decision-runtime')
    await expect(chapter.locator('.screen-decision').first()).toContainText('device panel')
    await expect(chapter.locator('.case-study-slide')).toHaveCount(3)
    await chapter.getByRole('button', {name:'Next Keep launch and runtime separate slide',exact:true}).click()
    await expect(chapter.locator('[role=status]')).toHaveText('2 / 3')
    const rail = chapter.locator('.case-study-slides__images')
    await rail.focus(); await page.keyboard.press('ArrowLeft')
    await expect(chapter.locator('[role=status]')).toHaveText('1 / 3')
    await chapter.locator('details').first().getByText('Read slide text',{exact:true}).click()
    await expect(chapter.locator('details[open] p').first()).toBeVisible()
    assert.equal(await chapter.evaluate(el => el.getAnimations({subtree:true}).some(a => a.effect?.getTiming().duration === 620)), false, 'proof animation under reduced motion')
    await overflow('Mentra')
    await page.screenshot({path:`${out}/mentra-${width}.png`})
    await page.route('**/Imagepdfportfolio.pdf', route => route.fulfill({status:503,body:'unavailable'}))
    await page.goto(base + '/book', {waitUntil:'domcontentloaded'})
    await expect(page.getByRole('heading',{name:'2022 Collection',exact:true})).toBeVisible()
    await expect(page.locator('.book-preloader')).toHaveCount(0)
    await expect(page.getByRole('button',{name:'Retry book',exact:true})).toBeVisible({timeout:20000})
    await page.getByRole('button',{name:'Retry book',exact:true}).click()
    await expect(page.getByRole('button',{name:'Retry book',exact:true})).toBeVisible()
    await overflow('Book')
    assert.deepEqual(errors, [])
    results.push({width,theme,passed:true})
    console.log(`${width}px: Work alignment and stable nav, About, six Notes, Mentra chapter controls, book failure recovery, reduced motion and overflow passed.`)
    await context.close()
  }
} finally { writeFileSync(out+'/results.json', JSON.stringify(results,null,2)); await browser.close() }
