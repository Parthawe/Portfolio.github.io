import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import { mkdirSync } from 'node:fs'
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5222', out = '/tmp/portfolio-site-refinement'
mkdirSync(out,{recursive:true})
const browser = await chromium.launch()
try {
 const context = await browser.newContext({viewport:{width:1440,height:960},reducedMotion:'no-preference',recordVideo:{dir:out,size:{width:1000,height:667}}})
 const page = await context.newPage()
 await page.addInitScript(() => { localStorage.setItem('theme','dark'); const original = Element.prototype.animate; window.__proofAnimations = []; Element.prototype.animate = function(frames,options){if(options?.duration === 620) window.__proofAnimations.push({tag:this.tagName,classes:this.className}); return original.call(this,frames,options)} })
 await page.goto(base+'/about#recognition',{waitUntil:'domcontentloaded'})
 await page.locator('.abt-recognition-ledger').scrollIntoViewIfNeeded()
 await expect.poll(()=>page.evaluate(()=>window.__proofAnimations.length)).toBeGreaterThan(0)
 await page.locator('.abt-vibe').scrollIntoViewIfNeeded()
 await expect(page.locator('.abt-vibe .abt-build-steps')).toBeVisible()
 await page.screenshot({path:out+'/about-code-desktop.png'})
 await page.goto(base+'/notes',{waitUntil:'domcontentloaded'})
 await page.getByRole('button',{name:'Hide examples',exact:true}).click()
 await page.getByRole('button',{name:/New note/}).click()
 await page.getByLabel('Your note',{exact:true}).fill('Local QA note, persistence check.')
 await page.getByRole('button',{name:'Post note',exact:true}).click()
 await page.reload()
 await expect(page.getByRole('article',{name:'Note from Anonymous',exact:true})).toContainText('Local QA note')
 await page.goto(base+'/book',{waitUntil:'domcontentloaded'})
 await expect(page.locator('.book-page-img').first()).toBeVisible({timeout:60000})
 await expect(page.getByRole('button',{name:'Next page',exact:true})).toBeEnabled()
 await page.getByRole('button',{name:'Next page',exact:true}).click()
 await expect(page.locator('.book-page-indicator').first()).not.toHaveText(/^1 \/ /)
 await page.getByLabel('Go to page',{exact:true}).selectOption('0')
 await expect(page.locator('.book-page-indicator').first()).toHaveText(/^1 \/ /)
 await page.locator('.book-viewer').focus(); await page.keyboard.press('ArrowRight')
 await expect(page.locator('.book-page-indicator').first()).not.toHaveText(/^1 \/ /)
 await page.screenshot({path:out+'/book-desktop.png'})
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
 await page.setViewportSize({width:390,height:844})
 await expect(page.locator('.book-mobile-page img')).toBeVisible(); assert((await page.locator('.book-mobile-page').boundingBox()).width > 300); await page.getByRole('button',{name:'Next page',exact:true}).click(); await expect(page.locator('.book-page-indicator').first()).toHaveText(/^3 \/ /)
 await page.screenshot({path:out+'/book-mobile.png'})
 console.log('PASS: normal-motion proof sequence, combined Code section, local Notes persistence, original PDF first pages, next/select/keyboard navigation, responsive book fit.')
 await context.close()
} finally { await browser.close() }
