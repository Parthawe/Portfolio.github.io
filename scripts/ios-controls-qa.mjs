import assert from 'node:assert/strict'
import { chromium, webkit, expect } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'
const base = process.env.QA_BASE_URL || 'http://127.0.0.1:5199'
const out = '/tmp/portfolio-ios-controls-qa'
mkdirSync(out, { recursive: true })
const results = [], errors = []
for (const [engine, profile] of [[chromium, 'desktop'], [chromium, 'mobile'], [webkit, 'mobile']]) {
 const browser = await engine.launch()
 try {
  for (const theme of ['light', 'dark']) {
   const context = await browser.newContext({ viewport: profile === 'mobile' ? { width: 375, height: 812 } : { width: 1185, height: 969 }, reducedMotion: 'reduce', hasTouch: profile === 'mobile' })
   await context.addInitScript(theme => { if (window.top === window) { try { localStorage.setItem('theme', theme) } catch {} } }, theme)
   const page = await context.newPage()
   page.on('pageerror', error => errors.push(`${engine.name()} ${profile} ${theme} ${page.url()}: ${error.message}`))
   await page.goto(`${base}/work`, { waitUntil: 'domcontentloaded' })
   if (profile === 'mobile') {
    const trigger = page.getByRole('button', { name: 'Open menu', exact: true })
    await trigger.click()
    const sheet = page.getByRole('dialog', { name: 'Site navigation' })
    await expect(sheet).toBeVisible()
    assert(await page.locator('#root').evaluate(root => root.inert), 'background is inert')
    const rect = await sheet.boundingBox()
    assert(rect.height < 812 * .75 && rect.y > 100, 'menu is a compact sheet')
    await page.screenshot({ path: `${out}/${engine.name()}-${profile}-${theme}-menu.png` })
    await page.keyboard.press('Shift+Tab')
    await expect(sheet.getByRole('link', { name: "Let's Talk", exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(sheet.getByRole('button', { name: 'Close site navigation' })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(sheet).toHaveCount(0)
    await expect(trigger).toBeFocused()
    assert(!(await page.locator('#root').evaluate(root => root.inert)), 'background restored')
    await trigger.click()
    await page.locator('.compact-sheet-backdrop').click({ position: { x: 20, y: 20 } })
    await expect(sheet).toHaveCount(0)
    await trigger.click()
    await sheet.getByRole('link', { name: 'About', exact: true }).click()
    await expect(page).toHaveURL(`${base}/about`)
    await expect(sheet).toHaveCount(0)
   } else {
    await page.getByRole('link', { name: 'Index', exact: true }).click()
    await expect(page.getByRole('link', { name: 'Index', exact: true })).toHaveAttribute('aria-current', 'page')
   }
   await page.goto(`${base}/shuffle`, { waitUntil: 'domcontentloaded' })
   const expand = page.locator('.cs-expand-preview-btn')
   await expect(expand).toBeVisible()
   await expand.click()
   await page.locator('#cs-interactive').scrollIntoViewIfNeeded()
   const chapter = page.locator('.cs-bnav-chapters')
   await expect(chapter).toBeVisible()
   await chapter.click()
   const chapters = profile === 'mobile' ? page.getByRole('dialog', { name: 'Case study chapters' }) : page.locator('.cs-bnav-menu.is-open')
   await expect(chapters).toBeVisible()
   assert(await chapters.getByRole('link').count() > 3)
   await page.screenshot({ path: `${out}/${engine.name()}-${profile}-${theme}-chapters.png` })
   const lastChapter = chapters.getByRole('link').last()
   const targetChapter = await lastChapter.getAttribute('href')
   await lastChapter.click()
   if (profile === 'mobile') {
    await expect(chapters).toHaveCount(0)
    assert(!(await page.locator('#root').evaluate(root => root.inert)))
    await expect(page.locator(targetChapter)).toBeFocused()
   } else await expect(chapters).toHaveCount(0)
   await page.goto(`${base}/moniac-machine/world`, { waitUntil: 'domcontentloaded' })
   const world = page.locator('.physical-world')
   await expect(world).toHaveAttribute('data-world-theme', theme)
   await world.getByRole('button', { name: 'Object', exact: true }).click()
   await expect(world.getByRole('button', { name: 'Object', exact: true })).toHaveAttribute('aria-pressed', 'true')
   await world.getByRole('button', { name: 'Reset', exact: true }).click()
   await expect(world.locator('[role="status"].sr-only')).toHaveText('Settings reset')
   await expect(world.getByRole('button', { name: 'Room', exact: true })).toHaveAttribute('aria-pressed', 'true')
   await world.locator('header').screenshot({ path: `${out}/${engine.name()}-${profile}-${theme}-camera.png` })
   assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'no horizontal overflow')
   await page.goto(`${base}/code-for-build/prototype`, { waitUntil: 'domcontentloaded' })
   const app = page.locator('[data-prototype]')
   await app.getByRole('button', { name: 'Code', exact: true }).click()
   await expect(app.getByRole('button', { name: 'Code', exact: true })).toHaveAttribute('aria-pressed', 'true')
   await expect(app.getByLabel('Generated HTML')).toBeVisible()
   await app.locator('.prototype-tabs').screenshot({ path: `${out}/${engine.name()}-${profile}-${theme}-tabs.png` })
   assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
   results.push(`${engine.name()} ${profile} ${theme}`)
   console.log(results.at(-1))
   await context.close()
  }
 } finally { await browser.close() }
}
writeFileSync(`${out}/report.json`, JSON.stringify({ results, errors }, null, 2))
assert.equal(errors.length, 0, errors.join('\n'))
console.log(`Passed ${results.length} profiles: sheets, focus, dismissal, selected controls, reset, themes and overflow.`)
